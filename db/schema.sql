-- Схема БД "Конструктор опросов".
-- Выполнять от имени владельца схемы (survey_owner).
-- Скрипт можно запускать повторно: он пересоздаёт таблицы с нуля (ДАННЫЕ УДАЛЯЮТСЯ).

SET ROLE survey_owner;

DROP TABLE IF EXISTS app.survey_answers        CASCADE;
DROP TABLE IF EXISTS app.survey_participations CASCADE;
DROP TABLE IF EXISTS app.question_options      CASCADE;
DROP TABLE IF EXISTS app.survey_questions      CASCADE;
DROP TABLE IF EXISTS app.surveys               CASCADE;
DROP TABLE IF EXISTS app.users                 CASCADE;

-- Пользователи системы
CREATE TABLE app.users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
    email      VARCHAR(255) UNIQUE,
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);

-- Опросы. Автор - пользователь; при удалении автора удаляются и его опросы.
CREATE TABLE app.surveys
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
    author_id  BIGINT       NOT NULL REFERENCES app.users (id) ON DELETE CASCADE,
    starts_at  TIMESTAMP,
    ends_at    TIMESTAMP,
    status     VARCHAR(20)  NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'ACTIVE', 'CLOSED')),
    created_at TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT surveys_dates_order
        CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);

-- Вопросы опроса
CREATE TABLE app.survey_questions
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id BIGINT       NOT NULL REFERENCES app.surveys (id) ON DELETE CASCADE,
    text      VARCHAR(500) NOT NULL CHECK (btrim(text) <> ''),
    required  BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Допустимые варианты ответа на вопрос (порядок сохраняется полем position)
CREATE TABLE app.question_options
(
    question_id BIGINT       NOT NULL REFERENCES app.survey_questions (id) ON DELETE CASCADE,
    position    INT          NOT NULL CHECK (position >= 0),
    value       VARCHAR(200) NOT NULL CHECK (btrim(value) <> ''),
    PRIMARY KEY (question_id, position),
    CONSTRAINT question_options_unique_value UNIQUE (question_id, value)
);

-- Участие пользователя в опросе. Один пользователь - одно участие в опросе.
CREATE TABLE app.survey_participations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id     BIGINT      NOT NULL REFERENCES app.surveys (id) ON DELETE CASCADE,
    respondent_id BIGINT      NOT NULL REFERENCES app.users (id) ON DELETE CASCADE,
    status        VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'ABANDONED')),
    started_at    TIMESTAMP   NOT NULL DEFAULT now(),
    submitted_at  TIMESTAMP,
    CONSTRAINT participations_one_per_user UNIQUE (survey_id, respondent_id),
    -- время отправки есть тогда и только тогда, когда участие отправлено
    CONSTRAINT participations_submitted_at
        CHECK ((status = 'SUBMITTED') = (submitted_at IS NOT NULL))
);

-- Ответы. Один ответ на вопрос в рамках участия.
CREATE TABLE app.survey_answers
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id BIGINT       NOT NULL REFERENCES app.survey_participations (id) ON DELETE CASCADE,
    question_id      BIGINT       NOT NULL REFERENCES app.survey_questions (id) ON DELETE CASCADE,
    value            VARCHAR(200) NOT NULL,
    CONSTRAINT answers_one_per_question UNIQUE (participation_id, question_id)
);

-- Индексы по внешним ключам (ускоряют поиск "все вопросы опроса" и т.п.)
CREATE INDEX idx_surveys_author      ON app.surveys (author_id);
CREATE INDEX idx_questions_survey    ON app.survey_questions (survey_id);
CREATE INDEX idx_participations_resp ON app.survey_participations (respondent_id);
CREATE INDEX idx_answers_question    ON app.survey_answers (question_id);

-- Права сервиса: только работа с данными, без изменения структуры
GRANT USAGE ON SCHEMA app TO survey_service;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO survey_service;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO survey_service;

RESET ROLE;